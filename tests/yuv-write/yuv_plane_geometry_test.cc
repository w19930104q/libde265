/*
  Acceptance test: plane geometry of decoded images (public API level).

  For every stream of the fixed sample matrix, decode all frames and assert,
  directly on the de265_image objects returned by the library:

    - the luma plane has the expected visible (conformance-window cropped)
      size;
    - the chroma plane sizes satisfy the sampling ratio of the chroma
      format, with ceil semantics for odd sizes:
        4:2:0 -> chroma = ceil(luma/2) x ceil(luma/2)
        4:2:2 -> chroma = ceil(luma/2) x luma
        4:4:4 -> chroma = luma x luma
        mono  -> no chroma planes (size 0x0)
    - the plane stride (in bytes) covers at least one row of samples;
    - the reported bit depth matches the stream.

  Usage: yuv_plane_geometry_test STREAMS_DIR
*/

#include "de265.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>

struct test_case {
  const char* file;
  de265_chroma chroma;
  int bitdepth;
  int luma_w, luma_h;   // visible size after conformance window cropping
  int frames;
};

static const test_case cases[] = {
  // streams as generated by x265 (104x64 coded, conformance window)
  { "c420_b08.h265",  de265_chroma_420,  8, 100, 60, 3 },
  { "c420_b10.h265",  de265_chroma_420, 10, 100, 60, 3 },
  { "c420_b12.h265",  de265_chroma_420, 12, 100, 60, 3 },
  { "c422_b08.h265",  de265_chroma_422,  8, 100, 60, 3 },
  { "c422_b10.h265",  de265_chroma_422, 10, 100, 60, 3 },
  { "c422_b12.h265",  de265_chroma_422, 12, 100, 60, 3 },
  { "c444_b08.h265",  de265_chroma_444,  8, 100, 60, 3 },
  { "c444_b10.h265",  de265_chroma_444, 10, 100, 60, 3 },
  { "c444_b12.h265",  de265_chroma_444, 12, 100, 60, 3 },
  { "cmono_b08.h265", de265_chroma_mono, 8, 100, 60, 3 },
  { "cmono_b10.h265", de265_chroma_mono,10, 100, 60, 3 },
  { "cmono_b12.h265", de265_chroma_mono,12, 100, 60, 3 },
  // streams with patched conformance window -> odd visible/chroma sizes
  { "p420_b08_odd.h265",  de265_chroma_420,  8, 102, 62, 3 },
  { "p420_b10_odd.h265",  de265_chroma_420, 10, 102, 62, 3 },
  { "p422_b08_odd.h265",  de265_chroma_422,  8, 102, 61, 3 },
  { "p444_b08_odd.h265",  de265_chroma_444,  8, 101, 61, 3 },
  { "p444_b10_odd.h265",  de265_chroma_444, 10, 101, 61, 3 },
  { "p444_b12_odd.h265",  de265_chroma_444, 12, 101, 61, 3 },
  { "pmono_b08_odd.h265", de265_chroma_mono, 8, 101, 61, 3 },
  { "pmono_b10_odd.h265", de265_chroma_mono,10, 101, 61, 3 },
};

static int failures = 0;

#define CHECK(cond, ...)                                              \
  do {                                                                \
    if (!(cond)) {                                                    \
      printf("FAIL %s: ", tc.file);                                   \
      printf(__VA_ARGS__);                                            \
      printf("\n");                                                   \
      failures++;                                                     \
    }                                                                 \
  } while (0)

static void check_image(const de265_image* img, const test_case& tc)
{
  CHECK(de265_get_chroma_format(img) == tc.chroma,
        "chroma format %d != expected %d",
        (int)de265_get_chroma_format(img), (int)tc.chroma);

  int lw = de265_get_image_width(img, 0);
  int lh = de265_get_image_height(img, 0);
  CHECK(lw == tc.luma_w && lh == tc.luma_h,
        "luma size %dx%d != expected %dx%d", lw, lh, tc.luma_w, tc.luma_h);

  int cw = de265_get_image_width(img, 1);
  int ch = de265_get_image_height(img, 1);

  // hardcoded sampling-ratio rules for the cropped picture
  int expect_cw = 0, expect_ch = 0;
  switch (tc.chroma) {
  case de265_chroma_420:  expect_cw = (lw+1)/2; expect_ch = (lh+1)/2; break;
  case de265_chroma_422:  expect_cw = (lw+1)/2; expect_ch = lh;       break;
  case de265_chroma_444:  expect_cw = lw;       expect_ch = lh;       break;
  case de265_chroma_mono: expect_cw = 0;        expect_ch = 0;        break;
  }

  CHECK(cw == expect_cw && ch == expect_ch,
        "chroma size %dx%d != expected %dx%d for luma %dx%d",
        cw, ch, expect_cw, expect_ch, lw, lh);

  // Cb and Cr planes must agree
  CHECK(de265_get_image_width(img, 2)  == cw &&
        de265_get_image_height(img, 2) == ch,
        "Cr plane size %dx%d != Cb plane size %dx%d",
        de265_get_image_width(img, 2), de265_get_image_height(img, 2), cw, ch);

  // bit depth and stride (stride is returned in bytes)
  int nPlanes = (tc.chroma == de265_chroma_mono) ? 1 : 3;
  for (int c = 0; c < nPlanes; c++) {
    int bits = de265_get_bits_per_pixel(img, c);
    CHECK(bits == tc.bitdepth, "plane %d bit depth %d != expected %d",
          c, bits, tc.bitdepth);

    int stride = 0;
    const uint8_t* p = de265_get_image_plane(img, c, &stride);
    CHECK(p != nullptr, "plane %d has no data", c);

    int w = de265_get_image_width(img, c);
    int bytes_per_sample = (bits + 7) / 8;
    CHECK(stride >= w * bytes_per_sample,
          "plane %d stride %d bytes < row of %d samples (%d bytes)",
          c, stride, w, w * bytes_per_sample);
  }
}

static void decode_stream(const char* path, const test_case& tc)
{
  FILE* fh = fopen(path, "rb");
  if (!fh) {
    printf("FAIL %s: cannot open\n", tc.file);
    failures++;
    return;
  }

  de265_decoder_context* ctx = de265_new_decoder();
  de265_set_parameter_bool(ctx, DE265_DECODER_PARAM_SUPPRESS_FAULTY_PICTURES,
                           false);

  int frames = 0;
  bool eof = false;
  while (!eof) {
    uint8_t buf[40960];
    size_t n = fread(buf, 1, sizeof(buf), fh);
    if (n > 0) {
      de265_push_data(ctx, buf, (int)n, 0, nullptr);
    }
    if (feof(fh)) {
      de265_flush_data(ctx);
      eof = true;
    }

    int more = 1;
    while (more) {
      more = 0;
      de265_error err = de265_decode(ctx, &more);
      if (err != DE265_OK && err != DE265_ERROR_IMAGE_BUFFER_FULL) {
        more = 0;
      }

      const de265_image* img;
      while ((img = de265_get_next_picture(ctx)) != nullptr) {
        check_image(img, tc);
        frames++;
      }
    }
  }

  CHECK(frames == tc.frames, "decoded %d frames != expected %d",
        frames, tc.frames);

  de265_free_decoder(ctx);
  fclose(fh);
}

int main(int argc, char** argv)
{
  if (argc != 2) {
    fprintf(stderr, "usage: %s STREAMS_DIR\n", argv[0]);
    return 2;
  }

  de265_disable_logging();

  for (const test_case& tc : cases) {
    char path[4096];
    snprintf(path, sizeof(path), "%s/%s", argv[1], tc.file);
    decode_stream(path, tc);
    printf("checked %s\n", tc.file);
  }

  if (failures) {
    printf("%d checks FAILED\n", failures);
    return 1;
  }

  printf("all plane geometry checks passed\n");
  return 0;
}
